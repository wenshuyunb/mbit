-- ============================================================================
-- ADR-030 第一步：关系状态枚举对齐接口契约
-- ============================================================================
--
-- 契约 §3.6 的状态集合是 `PENDING_A_CONFIRM | ACTIVE | REJECTED | EXPIRED | REMOVED`，
-- 而首版实现是 `PENDING_A_CONFIRM | ACTIVE | REJECTED | UNBOUND`：
--   · 缺 `EXPIRED` —— 契约 §3.6.6 要求「`PENDING_A_CONFIRM` 超 7 天置 `EXPIRED`」，
--     没有这个值，超时确认的定时任务无处落笔
--   · `UNBOUND` 与 `REMOVED` 语义重叠却是两个名字，同一状态在文档与代码里叫法不同
--
-- ⚠ 本迁移**必须**与 `20260217000000_relationship_pairkey_partial_unique`
--   分开执行，不可合并。原因见那个文件：它的部分唯一索引谓词引用
--   `'REMOVED'` 与 `'EXPIRED'`，而
--     · `ALTER TYPE ... RENAME VALUE` 的重命名效果在同一事务内对新建索引不可见
--     · `ALTER TYPE ... ADD VALUE` 更被 PG 明确禁止在同一事务内使用
--   合并成一个文件会直接报 `invalid input value for enum relationship_status`。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1) UNBOUND → REMOVED
-- ---------------------------------------------------------------------------
-- 用 `RENAME VALUE` 而非「建新类型 → ALTER COLUMN TYPE → 删旧类型」：
-- 前者原地改名，**不重写表**；后者要全表重写，在本表上（关系行会长期累积，
-- 且解绑/确认路径存在并发写入）重写期间的一致性代价明显更高。
-- PG 12+ 支持；本项目 compose 固定 PostgreSQL 16。
ALTER TYPE "relationship_status" RENAME VALUE 'UNBOUND' TO 'REMOVED';

-- ---------------------------------------------------------------------------
-- 2) 新增 EXPIRED
-- ---------------------------------------------------------------------------
-- 供「`PENDING_A_CONFIRM` 超 7 天」的定时任务写入。
-- 本文件不使用该值（PG 不允许在同一事务新增枚举值后立即使用），
-- 真正用到它的是下一个迁移的索引谓词与后续的关系超时任务。
ALTER TYPE "relationship_status" ADD VALUE IF NOT EXISTS 'EXPIRED';
