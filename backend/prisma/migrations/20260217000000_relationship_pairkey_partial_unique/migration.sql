-- ============================================================================
-- ADR-030 第二步：relationships.pairKey 唯一性改为部分唯一索引
-- ============================================================================
--
-- 背景：`pairKey` 原为**全表唯一**（`relationships_pair_key_key`）。接口契约
-- §3.6.7 要求「`pairKey` **保留原值**作审计，唯一性改为部分索引，使同一对
-- 用户可重新建立关系」。全表唯一会让**解绑后无法复合** —— 新关系会撞上旧行
-- 的唯一约束，而「解绑后又复合」是完全正常的用户旅程。
--
-- 依赖：`20260216000000_relationship_status_align_contract` 必须已经提交。
--       本文件的索引谓词引用 `'REMOVED'` / `'EXPIRED'`，这两个枚举值由那一步
--       引入；在同一事务内它们对谓词不可见，故不能合并。
--
-- ⚠ 本迁移是**破坏性**的（删唯一索引）。截至目前本项目尚未对真实 PostgreSQL
--   执行过任何迁移，因此本文件只做静态校验（`prisma validate` +
--   与 `prisma migrate diff` 输出比对）。
--
-- ⚠ Prisma schema 不支持带 `WHERE` 的索引，因此 `model Relationship` 里的
--   `@unique` 已移除，`relationships_pair_key_live_key` 只存在于本文件。
--   `prisma migrate diff` 会把它视为「数据库有、schema 无」的漂移，需在
--   DATABASE_DESIGN.md §7 索引清单登记并对这一条做白名单。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1) 删除旧的全表唯一索引
-- ---------------------------------------------------------------------------
-- 不删的话，第 2 步的部分唯一索引虽然建成了，旧索引仍会继续阻止复合 ——
-- 等于白改。`relationships_pair_key_key` 是 Prisma 为 `@unique` 生成的默认名。
DROP INDEX IF EXISTS "relationships_pair_key_key";

-- ---------------------------------------------------------------------------
-- 2) 建立部分唯一索引：同一对用户在「存活态」下最多一条关系
-- ---------------------------------------------------------------------------
-- 谓词**正向列举存活态**，而不是契约字面的 `status <> 'REMOVED'`：
--   · 契约字面写法会让 `REJECTED` / `EXPIRED` 的行继续占用唯一键 ——
--     A 误拒了 B 的邀请之后，两人将永远无法重新建立关系，这与本 ADR 要修的
--     缺陷是同一类
--   · 正向列举还有一个前瞻性好处：日后往枚举里新增终态（例如 `BLOCKED`）时，
--     `<>` 写法会**静默**把新终态也算作「占用唯一键」，重新引入该缺陷；
--     正向写法默认新值不占用，需要显式加入才会占用
-- 冲突时的语义（契约 §3.6.3）：捕获唯一冲突 → 回读并返回已有关系，绝不返回 500。
CREATE UNIQUE INDEX "relationships_pair_key_live_key"
    ON "relationships" ("pair_key")
    WHERE "status" IN ('PENDING_A_CONFIRM', 'ACTIVE');

-- ---------------------------------------------------------------------------
-- 3) 补普通索引：审计回溯「这对用户历史上建立过几次关系」
-- ---------------------------------------------------------------------------
-- 部分唯一索引查不到已进入终态的行，而契约 §3.6.5 的 timeline 与后台关系列表
-- 都需要跨全部历史记录查询 `pair_key`。
-- 索引名与 schema 里的 `@@index([pairKey])` 对齐，避免 `migrate diff` 再产生一条漂移。
CREATE INDEX "relationships_pair_key_idx" ON "relationships" ("pair_key");
