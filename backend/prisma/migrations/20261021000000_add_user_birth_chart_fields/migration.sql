-- ============================================================================
-- 出生信息扩展（星座星盘用）
-- ----------------------------------------------------------------------------
-- 背景：星座模块第一版只按「生日 → 太阳星座」出内容，无需出生时刻与地点。
-- 要做上升星座与宫位（用户要求的"更专业"）就必须知道：
--   · 出生时刻（精确到分钟）—— 上升星座每 2 小时左右换一个；
--   · 出生地纬度 —— 上升点的计算**只与纬度有关**；
--   · 出生地经度 + 时区偏移 —— 用来算当地恒星时（宫位需要）。
--
-- 五列全部可空：星座是可选功能，没填这些字段的用户只是看不到星盘，
-- 不该影响注册、测评与其它模块。既有行不受影响（NULL）。
--
-- ⚠ 时刻存 `VARCHAR(5)`（`HH:mm`）而不是 TIME/TIMESTAMPTZ：
-- 它表达的是"当地人看到的钟表时间"，折算 UTC 还要结合 birth_timezone_offset，
-- 用绝对时间类型会让"本地 08:30 出生于乌鲁木齐"被静默当成东八区同一瞬间。
-- ============================================================================

-- AlterTable
ALTER TABLE "users" ADD COLUMN "birth_time" VARCHAR(5),
ADD COLUMN "birth_place" VARCHAR(64),
ADD COLUMN "birth_latitude" DOUBLE PRECISION,
ADD COLUMN "birth_longitude" DOUBLE PRECISION,
ADD COLUMN "birth_timezone_offset" DOUBLE PRECISION;
