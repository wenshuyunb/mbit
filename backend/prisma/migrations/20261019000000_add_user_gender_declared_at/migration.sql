-- ADR-039（情感测评改为沉浸式场景题 + 按性别出题）的第一步：性别基座
--
-- ## 加这一列解决什么问题
--
-- `users.gender` 已经存在（`UNKNOWN` / `MALE` / `FEMALE` / `OTHER`，默认 `UNKNOWN`），
-- 但 `UNKNOWN` 有两种截然不同的来源：
--
--   ① **从来没问过**用户性别（现状：小程序端没有任何性别入口，所以所有人都落在这里）
--   ② 问过了，用户**选择不说**
--
-- 两者的取题结果相同（都取中性版场景），但交互必须不同：
-- 前者要弹引导，后者不该反复弹。只看 `gender` 无法区分这两者，
-- 直接照 `gender = UNKNOWN` 判断就会出现「选了不想说的人每次进来都被再问一遍」。
--
-- 因此单独记一个「**被询问过**的时间」：用户做出选择时置位（**包括选择"不想说"**），
-- 改性别时不再重置。语义是"问过了"，不是"填了"。
--
-- ## 为什么此时还没有 questions.audience 等列
--
-- 场景题的题型打通（`questions.audience`、场景叙述与选项即时反馈）
-- 属于 ADR-039 的第二步，与这一列没有依赖关系，分两次迁移便于各自独立验证。
ALTER TABLE "users" ADD COLUMN "gender_declared_at" TIMESTAMPTZ(3);
