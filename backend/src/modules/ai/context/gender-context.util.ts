/**
 * 报告提示词的**性别语境**（ADR-039）
 *
 * ## 为什么是"语境"而不是"性别化结论"
 *
 * 用户要求"报告也按性别出"。但测量结论本身**不能**按性别变：
 * 同一份依恋焦虑分数在男女身上是同一个分数，MBTI 类型也不会因为性别换一个字母。
 * 一旦让性别参与结论，报告就从"测量结果"变成"社会角色期待" —— 那既不准，
 * 也会让男生版与女生版的分数量纲不再可比。
 *
 * 因此性别只影响三件事，且都必须写死在提示词里：
 *   ① **举例与称呼**：用「你和她」「你和他」这类与用户一致的指代；
 *   ② **处境的选取**：举的例子要贴用户真实会遇到的情形；
 *   ③ **禁止刻板印象**：显式禁止"男生不该……""女生都……"这类归因 ——
 *      这句话必须写进提示词，否则模型几乎一定会顺手写出来。
 *
 * ## 未提供性别时用中性措辞
 *
 * `UNKNOWN` / `OTHER` / 读不到记录 → 一律中性（「对方」「TA」），
 * 并且**明确要求不要询问、也不要猜测**：报告里冒出一句"作为女生……"
 * 对选了「不想说」的用户是直接的冒犯。
 */

/** 归一化后的性别语境类别 */
export type ReportGenderFraming = 'MALE' | 'FEMALE' | 'NEUTRAL';

/** 把数据库里的性别值归一到三档语境（未知与"不想说"都走中性） */
export const resolveReportGenderFraming = (gender: string | null | undefined): ReportGenderFraming => {
  if (gender === 'MALE') return 'MALE';
  if (gender === 'FEMALE') return 'FEMALE';

  return 'NEUTRAL';
};

/**
 * 组装注入提示词的性别语境段落
 *
 * ⚠ 返回值**永远是可用文本**（没有"未提供"占位）：未提供性别时给出的
 * 是"用中性措辞"的**明确指令**，而不是一句"（本项缺失）"——
 * 后者会让模型自行脑补一个性别，而这份报告是要给用户看的。
 */
export const buildGenderContext = (gender: string | null | undefined): string => {
  const framing = resolveReportGenderFraming(gender);

  const common = [
    '性别只影响**举例、称呼与处境的选取**，不影响任何结论：',
    '同一个分数在男生与女生身上是同一个分数，不要因为性别调整任何判断、等级或建议。',
    '🚫 严禁性别刻板印象：不要写"男生不该……""女生都……""作为男性/女性就应该……"这类表述，',
    '也不要把性别当作某个分数的解释（"因为你是男生，所以……"）。',
  ].join('\n');

  if (framing === 'MALE') {
    return ['用户自述为**男生**。举例与称呼请按男生视角展开（如「你和她」「你女朋友」，或用「伴侣」）。', common].join(
      '\n',
    );
  }

  if (framing === 'FEMALE') {
    return ['用户自述为**女生**。举例与称呼请按女生视角展开（如「你和他」「你男朋友」，或用「伴侣」）。', common].join(
      '\n',
    );
  }

  return [
    '用户**未提供性别**（或选择不说）。一律使用中性措辞：「对方」「伴侣」「TA」，',
    '🚫 不要假设、不要询问、也不要提及性别，更不要出现"作为男性/女性……"这类表述。',
    common,
  ].join('\n');
};
