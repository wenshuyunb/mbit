/** 大阿卡纳（逐张内容） */
export const TAROT_MAJOR: readonly TarotCard[] = MAJOR_ROWS.map((row) => {
  const [numeral, name, symbol, keywords, upright, reversed] = row;

  return {
    id: `MAJOR-${numeral.padStart(2, '0')}`,
    arcana: 'MAJOR' as const,
    numeral,
    suit: null,
    rank: null,
    name,
    symbol,
    keywords,
    upright,
    reversed,
  };
});

/**
 * 小阿卡纳的逐张关键词
 *
 * 只写关键词（`[正位关键词, 逆位关键词]`），正文由 `buildMinorMeaning` 按
 * 「花色领域 × 位阶阶段」组合生成。这样 56 张的差异来自关键词，而不是硬编 56 段水话。
 */
const MINOR_KEYWORDS: Readonly<Record<TarotRank, readonly [string, string]>> = {
  ACE: ['起点', '启动困难'],
  TWO: ['平衡', '摇摆'],
  THREE: ['成形', '分散'],
  FOUR: ['稳定', '僵住'],
  FIVE: ['摩擦', '逃避'],
  SIX: ['回稳', '反复'],
  SEVEN: ['评估', '纠缠'],
  EIGHT: ['推进', '失控'],
  NINE: ['临界', '耗损'],
  TEN: ['收尾', '过载'],
  PAGE: ['学习', '不成熟'],
  KNIGHT: ['行动', '莽撞'],
  QUEEN: ['内化', '过度付出'],
  KING: ['掌控', '僵化'],
};

/** 花色在不同位阶上的具体落点（让组合出来的句子不空） */
const SUIT_ACTIONS: Readonly<Record<TarotSuit, readonly [string, string, string]>> = {
  WANDS: ['动手做点什么', '推进一件正在做的事', '把热情落到具体动作上'],
  CUPS: ['把感受说出来', '照顾一段关系里的情绪', '允许自己有情绪'],
  SWORDS: ['把话说清楚', '想清楚再决定', '处理一个回避的对话'],
  PENTACLES: ['把现实的事安排好', '处理钱与时间', '让基础更稳一点'],
};

/**
 * 组合出小阿卡纳的正文
 *
 * 结构固定为「花色领域 → 位阶阶段 → 今天可做的一件小事」，
 * 三部分各自有真实含义，拼起来是一句具体的话，而不是形容词堆叠。
 */
export const buildMinorMeaning = (suit: TarotSuit, rank: TarotRank, orientation: 'UPRIGHT' | 'REVERSED'): string => {
  const suitInfo = TAROT_SUIT_LABELS[suit];
  const rankInfo = TAROT_RANK_LABELS[rank];
  const [uprightKeyword, reversedKeyword] = MINOR_KEYWORDS[rank];
  const action = SUIT_ACTIONS[suit];

  if (orientation === 'UPRIGHT') {
    return `${suitInfo.name}属于「${suitInfo.domain}」，${rankInfo.name}对应「${rankInfo.stage}」。这张牌落在正位，提示这个领域正处在「${uprightKeyword}」的状态：适合${action[0]}，让它在现实里有个具体的落点。`;
  }

  return `${suitInfo.name}属于「${suitInfo.domain}」，${rankInfo.name}对应「${rankInfo.stage}」。这张牌逆位不代表坏消息，而是这股能量受阻或过量，容易表现成「${reversedKeyword}」：可能是${action[1]}这一步一直没做成，也可能做得太用力。今天先把节奏调回来。`;
};

/** 小阿卡纳（56 张，关键词 + 组合正文） */
export const TAROT_MINOR: readonly TarotCard[] = TAROT_SUITS.flatMap((suit) =>
  TAROT_RANKS.map((rank) => {
    const suitInfo = TAROT_SUIT_LABELS[suit];
    const rankInfo = TAROT_RANK_LABELS[rank];
    // 逆位关键词只用于 `buildMinorMeaning` 生成的正文里，卡面关键词取正位
    const [uprightKeyword] = MINOR_KEYWORDS[rank];

    return {
      id: `${suit}-${rank}`,
      arcana: 'MINOR' as const,
      numeral: null,
      suit,
      rank,
      name: `${suitInfo.name}${rankInfo.name}`,
      symbol: suitInfo.symbol,
      keywords: [uprightKeyword, suitInfo.domain],
      upright: buildMinorMeaning(suit, rank, 'UPRIGHT'),
      reversed: buildMinorMeaning(suit, rank, 'REVERSED'),
    };
  }),
);

/** 完整 78 张牌（大阿卡纳在前，符合传统牌序） */
export const TAROT_DECK: readonly TarotCard[] = [...TAROT_MAJOR, ...TAROT_MINOR];
